  await expect(live.locator('[data-block="hero"]')).toHaveAttribute('data-review-active', 'true')
  await expect(proposed.locator('[data-block="hero"]')).toHaveAttribute('data-review-active', 'true')
  await reviewer.page.getByRole('button', { name: 'Live', exact: true }).click()
