  expect(rejectedSecond.ok(), await rejectedSecond.text()).toBeTruthy()
  await reviewer.page.emulateMedia({ reducedMotion: 'reduce' })
  await reviewer.page.setViewportSize({ width: 390, height: 844 })
  await expect(reviewer.page.getByRole('complementary', { name: 'Pending page review' })).toBeVisible()
  expect(await reviewer.page.evaluate(async () => (await (window as unknown as { axe: typeof import('axe-core') }).axe.run('[data-public-page-review]', { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag22aa'] } })).violations)).toEqual([])
